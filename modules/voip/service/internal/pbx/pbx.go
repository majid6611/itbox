// Package pbx turns what the admin set up in the panel into Asterisk's
// own config files. Everything Asterisk needs to know about this office's
// phones is regenerated from scratch on every change — three small files,
// so there's no diffing or partial update to get wrong — then Asterisk is
// told to reload them.
//
// Every value written here has already passed the Valid* checks below,
// which is what keeps a name or password from breaking out of its line:
// Asterisk's config format treats ';' as a comment and has no quoting
// for most values, so anything that could be read as syntax is rejected
// rather than escaped.
package pbx

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type Extension struct {
	Number      string
	Name        string
	Password    string
	InMainGroup bool
}

// IVROption is one key of the phone menu: pressing Digit rings Targets
// (extension numbers) together.
type IVROption struct {
	Digit   string
	Label   string
	Targets []string
}

// IVR is the phone menu callers from outside hear: a recorded greeting and
// one level of keys. It only takes effect when Enabled and a greeting file
// actually exists.
type IVR struct {
	Enabled     bool
	HasGreeting bool
	// Recorder is the one extension that may re-record the greeting by
	// dialing *99 ("" = nobody).
	Recorder string
	Options  []IVROption
}

// GreetingBase is where the greeting lives inside the asterisk container
// (no extension: Asterisk picks the format it finds). The voip service sees
// the same volume at its own path — see api.Server.SoundsDir.
const GreetingBase = "/var/lib/itp-sounds/greeting"

type Settings struct {
	TrunkEnabled       bool
	TrunkHost          string
	TrunkUsername      string
	TrunkPassword      string
	TrunkCallerID      string
	AllowInternational bool
}

var (
	// 2-5 digits, not starting with 0 (dial 0 = main number) or 9 (dial
	// 9 = outside line).
	numberRe   = regexp.MustCompile(`^[1-8][0-9]{1,4}$`)
	nameRe     = regexp.MustCompile(`^[\p{L}\p{N} .'()&_-]{1,40}$`)
	hostRe     = regexp.MustCompile(`^[A-Za-z0-9.-]{1,253}(:[0-9]{1,5})?$`)
	userRe     = regexp.MustCompile(`^[A-Za-z0-9._+-]{1,64}$`)
	passRe     = regexp.MustCompile(`^[!-:<-~]{1,128}$`) // printable ASCII, no space or ';'
	callerIDRe = regexp.MustCompile(`^\+?[0-9]{0,20}$`)
	digitRe    = regexp.MustCompile(`^[1-9]$`)
)

func ValidDigit(s string) bool { return digitRe.MatchString(s) }

func ValidNumber(s string) bool        { return numberRe.MatchString(s) }
func ValidName(s string) bool          { return nameRe.MatchString(s) }
func ValidTrunkHost(s string) bool     { return hostRe.MatchString(s) }
func ValidTrunkUsername(s string) bool { return userRe.MatchString(s) }
func ValidTrunkPassword(s string) bool { return passRe.MatchString(s) }
func ValidCallerID(s string) bool      { return callerIDRe.MatchString(s) }

// Render returns the generated files' contents by file name.
func Render(exts []Extension, st Settings, ivr IVR) map[string]string {
	trunk := st.TrunkEnabled && st.TrunkHost != "" && st.TrunkUsername != ""
	return map[string]string{
		"pjsip.conf":      renderPJSIP(exts, st, trunk),
		"extensions.conf": renderDialplan(exts, st, trunk, ivr),
		"voicemail.conf":  renderVoicemail(exts),
	}
}

const header = "; Generated by the IT Platform phone module — edits here are overwritten.\n\n"

// lanOnly restricts where an office phone may connect from: private
// networks and the VPN (100.64.0.0/10 is NetBird's range). Asterisk
// shares the host's network, so on a server that also has a public
// interface a leaked phone password would otherwise work from anywhere.
// Per-extension rather than a global ACL so the outside-line provider,
// which calls in from a public address, isn't blocked too.
//
// acl checks the address the packets really come from (itp-lan in
// asterisk/conf/acl.conf). The contact_* lines only check the address a
// phone says it has in its own Contact header, which anyone can write, so
// they are a second layer, not the protection.
const lanOnly = `acl = itp-lan
contact_deny = 0.0.0.0/0.0.0.0
contact_permit = 10.0.0.0/255.0.0.0
contact_permit = 172.16.0.0/255.240.0.0
contact_permit = 192.168.0.0/255.255.0.0
contact_permit = 100.64.0.0/255.192.0.0
`

func renderPJSIP(exts []Extension, st Settings, trunk bool) string {
	var b strings.Builder
	b.WriteString(header)
	for _, e := range exts {
		fmt.Fprintf(&b, `[%[1]s](itp-endpoint)
context = itp-internal
disallow = all
allow = g722,ulaw,alaw
auth = %[1]s
aors = %[1]s
callerid = "%[2]s" <%[1]s>
mailboxes = %[1]s@default
direct_media = no
rtp_symmetric = yes
force_rport = yes
rewrite_contact = yes
%[4]s
[%[1]s]
type = auth
auth_type = userpass
username = %[1]s
password = %[3]s

[%[1]s]
type = aor
max_contacts = 2
remove_existing = yes
qualify_frequency = 30

`, e.Number, e.Name, e.Password, lanOnly)
	}
	if trunk {
		fmt.Fprintf(&b, `[trunk-auth]
type = auth
auth_type = userpass
username = %[2]s
password = %[3]s

[trunk-reg]
type = registration
outbound_auth = trunk-auth
server_uri = sip:%[1]s
client_uri = sip:%[2]s@%[1]s
retry_interval = 60
forbidden_retry_interval = 600

[trunk]
type = aor
contact = sip:%[1]s

[trunk](itp-endpoint)
context = itp-incoming
disallow = all
allow = ulaw,alaw,g722
outbound_auth = trunk-auth
aors = trunk
from_user = %[2]s
from_domain = %[4]s
direct_media = no
rtp_symmetric = yes
force_rport = yes
rewrite_contact = yes

[trunk-identify]
type = identify
endpoint = trunk
match = %[4]s

`, st.TrunkHost, st.TrunkUsername, st.TrunkPassword, hostOnly(st.TrunkHost))
	}
	return b.String()
}

func renderDialplan(exts []Extension, st Settings, trunk bool, ivr IVR) string {
	var b strings.Builder
	b.WriteString(header)
	menu := renderMenu(exts, ivr)

	// What every office phone can dial.
	b.WriteString("[itp-internal]\n")
	for _, e := range exts {
		fmt.Fprintf(&b, "exten => %[1]s,1,Dial(PJSIP/%[1]s,25)\n same => n,VoiceMail(%[1]s@default,u)\n same => n,Hangup()\n", e.Number)
	}
	// Mailbox from the calling phone's own endpoint, not its caller ID —
	// a phone can put anything it likes in its From header, but not
	// change which account it authenticated as. Same reason both skip
	// the PIN prompt (the s option): only a registered office phone can
	// reach these at all.
	// Staff dialing 0 go straight to the main group: the menu is for callers
	// from outside.
	b.WriteString(`exten => 0,1,Goto(itp-ring,s,1)
exten => *97,1,VoiceMailMain(${CHANNEL(endpoint)}@default,s)
 same => n,Hangup()
exten => *98,1,VoiceMailMain(0@default,s)
 same => n,Hangup()
exten => *43,1,Answer()
 same => n,Playback(demo-echotest)
 same => n,Echo()
 same => n,Hangup()
`)
	if menu != "" {
		// Lets an admin hear exactly what an outside caller hears.
		b.WriteString("exten => *50,1,Goto(itp-ivr,s,1)\n")
	}
	if ivr.Recorder != "" && ValidNumber(ivr.Recorder) {
		// Only the chosen extension may replace the company greeting; the
		// endpoint is the account the phone authenticated as, which a phone
		// can't fake. Beep, speak, press # (or stop talking for 5 seconds),
		// then it plays the result back. A hang-up keeps what was said.
		fmt.Fprintf(&b, `exten => *99,1,GotoIf($["${CHANNEL(endpoint)}" = "%s"]?ok)
 same => n,Playback(ss-noservice)
 same => n,Hangup()
 same => n(ok),Answer()
 same => n,Wait(1)
 same => n,Record(%s.wav,5,120,k)
 same => n,Wait(1)
 same => n,Playback(%s)
 same => n,Hangup()
`, ivr.Recorder, GreetingBase, GreetingBase)
	}
	if trunk {
		b.WriteString("exten => _9X.,1,NoOp(outside call)\n")
		if !st.AllowInternational {
			// Off by default: a leaked phone password is far cheaper when
			// it can't reach premium international numbers. 00 is the
			// international prefix almost everywhere, 011 in North America.
			b.WriteString(" same => n,GotoIf($[\"${EXTEN:1:2}\" = \"00\"]?blocked)\n")
			b.WriteString(" same => n,GotoIf($[\"${EXTEN:1:3}\" = \"011\"]?blocked)\n")
		}
		if st.TrunkCallerID != "" {
			fmt.Fprintf(&b, " same => n,Set(CALLERID(num)=%s)\n", st.TrunkCallerID)
		}
		b.WriteString(" same => n,Dial(PJSIP/${EXTEN:1}@trunk,60)\n same => n,Hangup()\n")
		b.WriteString(" same => n(blocked),Playback(ss-noservice)\n same => n,Hangup()\n")
	}
	b.WriteString("\n")

	// The main number. With a phone menu set up, outside callers hear it
	// first; otherwise (and as the fallback) it rings everyone in the main
	// group at once, then the shared mailbox (checked with *98).
	var members []string
	for _, e := range exts {
		if e.InMainGroup {
			members = append(members, "PJSIP/"+e.Number)
		}
	}
	b.WriteString("[itp-main]\nexten => s,1,NoOp(main number)\n")
	if menu != "" {
		b.WriteString(" same => n,Goto(itp-ivr,s,1)\n\n")
	} else {
		b.WriteString(" same => n,Goto(itp-ring,s,1)\n\n")
	}
	b.WriteString("[itp-ring]\nexten => s,1,NoOp(ring the main group)\n")
	if len(members) > 0 {
		fmt.Fprintf(&b, " same => n,Dial(%s,30)\n", strings.Join(members, "&"))
	}
	b.WriteString(" same => n,VoiceMail(0@default,u)\n same => n,Hangup()\n\n")
	b.WriteString(menu)

	// Calls coming in from the outside line, whatever number the
	// provider says was dialed.
	b.WriteString("[itp-incoming]\nexten => s,1,Goto(itp-main,s,1)\nexten => _[+0-9].,1,Goto(itp-main,s,1)\n")
	return b.String()
}

func renderVoicemail(exts []Extension) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("[default]\n0 => 0000,Main number\n")
	for _, e := range exts {
		// The PIN is never asked for (see VoiceMailMain's s option above),
		// but the format requires one.
		fmt.Fprintf(&b, "%s => 0000,%s\n", e.Number, e.Name)
	}
	return b.String()
}

func hostOnly(hostPort string) string {
	h, _, _ := strings.Cut(hostPort, ":")
	return h
}

// Write replaces the generated files in dir. Each goes through a temp
// file + rename so Asterisk never reads a half-written one.
func Write(dir string, files map[string]string) error {
	for name, content := range files {
		tmp := filepath.Join(dir, "."+name+".tmp")
		if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", name, err)
		}
		if err := os.Rename(tmp, filepath.Join(dir, name)); err != nil {
			return fmt.Errorf("rename %s: %w", name, err)
		}
	}
	return nil
}

// renderMenu writes the phone menu context, or "" when there is none to
// offer (switched off, no greeting recorded yet, or no key that still points
// at an existing extension). One level only: a key rings people, it never
// opens another menu.
func renderMenu(exts []Extension, ivr IVR) string {
	if !ivr.Enabled || !ivr.HasGreeting {
		return ""
	}
	exists := make(map[string]bool, len(exts))
	for _, e := range exts {
		exists[e.Number] = true
	}
	var b strings.Builder
	keys := 0
	for _, o := range ivr.Options {
		var dial []string
		var first string
		for _, t := range o.Targets {
			if exists[t] {
				if first == "" {
					first = t
				}
				dial = append(dial, "PJSIP/"+t)
			}
		}
		if len(dial) == 0 || !ValidDigit(o.Digit) {
			continue
		}
		// One person: their own voicemail. A group: the shared mailbox.
		mailbox := "0"
		if len(dial) == 1 {
			mailbox = first
		}
		fmt.Fprintf(&b, "; %s = %s\nexten => %s,1,NoOp(menu key %s)\n same => n,Dial(%s,25)\n same => n,VoiceMail(%s@default,u)\n same => n,Hangup()\n",
			o.Digit, o.Label, o.Digit, o.Digit, strings.Join(dial, "&"), mailbox)
		keys++
	}
	if keys == 0 {
		return ""
	}
	// Nothing pressed or a key that isn't on the menu: one more go, then the
	// main group. 0 always reaches the main group.
	return "[itp-ivr]\nexten => s,1,Answer()\n same => n,Set(TRIES=0)\n" +
		" same => n(menu),Background(" + GreetingBase + ")\n same => n,WaitExten(6)\n" +
		b.String() +
		"exten => 0,1,Goto(itp-ring,s,1)\n" +
		"exten => t,1,Set(TRIES=$[${TRIES}+1])\n" +
		" same => n,GotoIf($[${TRIES}>=2]?ring)\n same => n,Goto(s,menu)\n same => n(ring),Goto(itp-ring,s,1)\n" +
		"exten => i,1,Playback(pbx-invalid)\n same => n,Goto(t,1)\n\n"
}
